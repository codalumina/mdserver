"""
Economic Calendar Routing Module.

Because the MetaTrader 5 Python library does not expose the native economic 
calendar, this module bridges the gap by parsing CSV exports generated by a 
background MQL5 Expert Advisor. It handles currency filtering, importance 
weighting, and strict UTC normalizations.
"""

import csv
import os
from datetime import datetime, timezone
from fastapi import APIRouter, HTTPException, Query, status

from core.mt5_engine import engine
from core.logger import logger
from schemas.mt5 import CalendarResponse, CalendarEvent

router = APIRouter()

@router.get("/", response_model=CalendarResponse)
def economic_calendar(
    importance: str = Query("2,3"),
    currency: str = Query("USD,EUR,GBP,JPY,AUD,CAD,CHF,NZD")
):
    """
    Retrieve and filter upcoming macroeconomic events.
    
    This function dynamically locates the MT5 data folder (compatible with both 
    native Windows and WINE environments) to read the `calendar_export.csv` file. 
    It normalizes all MQL5 integer timestamps into standard UTC ISO strings.
    
    Args:
        importance (str): Comma-separated list of event weights (e.g., '2,3' for High/Med).
        currency (str): Comma-separated list of target currencies (e.g., 'USD,EUR').
        
    Note on missing values: MT5 represents empty calendar fields with a specific 
    minimum long integer (-9223372036854775808). This function intercepts that 
    value and safely converts it to Python's `None`.
    """

    # Dynamically locate the MT5 data path (works on WINE and Native Windows)
    terminal_info = engine.get_terminal_info()
    data_path = terminal_info.get("data_path")
    
    if not data_path:
        raise HTTPException(status_code=500, detail="Failed to retrieve MT5 data path.")
        
    calendar_csv_path = os.path.join(data_path, "MQL5", "Files", "calendar_export.csv")

    if not os.path.exists(calendar_csv_path):
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE, 
            detail=f"Calendar data file not found at {calendar_csv_path}. Ensure MQL5 EA is running."
        )

    allowed_importance = [int(i.strip()) for i in importance.split(",")] if importance else []
    allowed_currencies = [c.strip().upper() for c in currency.split(",")] if currency else []

    events = []
    LONG_MIN = "-9223372036854775808"

    try:
        with open(calendar_csv_path, "r", encoding="windows-1252", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if allowed_importance and int(row["importance"]) not in allowed_importance:
                    continue
                if allowed_currencies and row["currency"] not in allowed_currencies:
                    continue

                raw_time = int(row["time"])
                utc_ts, iso_str = engine._normalize_time(raw_time)

                def parse_val(val_str):
                    return None if val_str == LONG_MIN or not val_str else float(val_str) / 1000000.0

                events.append(CalendarEvent(
                    time=utc_ts,
                    iso_time=iso_str,
                    event_id=row["event_id"],
                    event_name=row["event_name"],
                    currency=row["currency"],
                    country=row.get("country", "N/A"),
                    importance=int(row["importance"]),
                    actual=parse_val(row["actual_value"]),
                    forecast=parse_val(row["forecast_value"]),
                    previous=parse_val(row["prev_value"]),
                ))

        events.sort(key=lambda x: x.time)
        return CalendarResponse(
            count=len(events),
            events=events,
            timestamp=datetime.now(timezone.utc).isoformat()
        )
    except Exception as e:
        logger.error(f"Calendar parsing failed: {e}")
        raise HTTPException(status_code=500, detail=str(e))